#!/usr/bin/env node
/**
 * Dump the canonical Zode library.
 *
 * The web app is the single source of truth for the records. This script
 * imports it directly (it is plain ESM with zero dependencies) and prints the
 * fully-resolved library as JSON — ids, durations, track numbers, playlists
 * and all — so that the iOS and Android clients can present *exactly* the
 * same library instead of inventing their own.
 *
 * Usage:  node scripts/dump_library.mjs
 */

import {
  ARTISTS,
  ALBUMS,
  TRACKS,
  PLAYLISTS,
  METRO_ART_PALETTE,
} from '../apps/web/src/data/library.js';

const albumGenre = new Map(ALBUMS.map((album) => [album.id, album.genre]));
const albumArtistName = new Map(ARTISTS.map((artist) => [artist.id, artist.name]));

/**
 * The flat accent colour of an album tile.
 *
 * The web app paints a gradient built from the Metro accent palette; the
 * native clients paint a flat tile, so they use the palette entry's leading
 * colour. Both come from the same list, so the two agree.
 *
 * @param {string} id e.g. "alb-01"
 * @returns {string} "#rrggbb"
 */
function accentHex(id) {
  const suffix = Number((id.match(/(\d+)\s*$/) || [])[1] ?? NaN);
  const index = Number.isFinite(suffix)
    ? (suffix - 1) % METRO_ART_PALETTE.length
    : 0;
  return METRO_ART_PALETTE[index].a;
}

const data = {
  $comment:
    'Canonical Zode library. Generated by scripts/dump_library.mjs from ' +
    'apps/web/src/data/library.js. Every platform MUST present exactly these records.',
  version: 1,
  artists: ARTISTS.map((artist) => ({
    id: artist.id,
    name: artist.name,
    genre: artist.genre,
    albumIds: artist.albumIds,
  })),
  albums: ALBUMS.map((album) => ({
    id: album.id,
    title: album.title,
    artistId: album.artistId,
    artistName: album.artistName,
    year: album.year,
    genre: album.genre,
    trackIds: album.trackIds,
    accentHex: accentHex(album.id),
  })),
  tracks: TRACKS.map((track) => ({
    id: track.id,
    title: track.title,
    albumId: track.albumId,
    albumTitle: track.albumTitle,
    artistId: track.artistId,
    artistName: track.artistName,
    duration: track.duration,
    trackNumber: track.trackNumber,
    year: track.year,
    genre: albumGenre.get(track.albumId) ?? '',
  })),
  playlists: PLAYLISTS.map((playlist) => ({
    id: playlist.id,
    title: playlist.title,
    description: playlist.description,
    trackIds: playlist.trackIds,
  })),
  palette: METRO_ART_PALETTE,
};

process.stdout.write(`${JSON.stringify(data, null, 2)}\n`);
