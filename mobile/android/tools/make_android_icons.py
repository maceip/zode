#!/usr/bin/env python3
"""Generate the Android launcher icons for Zode.

Standard library only (plus `pnglib.py` / `iconart.py` from
`mobile/tools/`). Run it from the repository root:

    python3 mobile/android/tools/make_android_icons.py

It produces:

  * `res/mipmap-<density>/ic_launcher.png`      -- the legacy launcher icon
  * `res/mipmap-<density>/ic_launcher_round.png` -- the round variant
  * `res/mipmap-<density>/ic_launcher_foreground.png` -- the adaptive foreground
  * `res/mipmap-anydpi-v26/ic_launcher.xml`      -- the adaptive icon
  * `res/mipmap-anydpi-v26/ic_launcher_round.xml`
  * `res/values/colors.xml`                      -- the adaptive background colour

The art comes from `icons/zode.png` (the product icon). The adaptive
foreground holds only the Zune bracket mark, scaled to sit inside the 66%
safe zone of the 108dp adaptive canvas, so no launcher mask clips it.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
# `pnglib.py` and `iconart.py` live in the shared mobile/tools folder.
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))

import iconart  # noqa: E402
import pnglib  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[3]
SOURCE_ICON = REPO_ROOT / "icons" / "zode.png"
RES_DIR = REPO_ROOT / "mobile" / "android" / "app" / "src" / "main" / "res"

# density suffix -> (launcher icon px, adaptive foreground px)
DENSITIES = {
    "mdpi": (48, 108),
    "hdpi": (72, 162),
    "xhdpi": (96, 216),
    "xxhdpi": (144, 324),
    "xxxhdpi": (192, 432),
}

# The adaptive icon canvas is 108dp; the art must stay inside 66dp.
SAFE_ZONE = 66.0 / 108.0


def write_legacy(plate, glyph, size: int, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    pnglib.write_png(str(path), iconart.legacy_icon(plate, glyph, size))


def write_foreground(glyph, canvas: int, path: Path) -> None:
    """Place the mark inside the 66% safe zone of the adaptive canvas."""
    path.parent.mkdir(parents=True, exist_ok=True)

    left, top, width, height = iconart.mark_bounds(glyph)
    if width == 0:
        raise SystemExit("Could not find the bracket glyph in %s" % SOURCE_ICON)

    mark = glyph.crop(left, top, width, height)

    # Fit the mark into the safe zone, keeping its aspect ratio.
    safe = int(round(canvas * SAFE_ZONE))
    scale = min(safe / width, safe / height)
    target_width = max(1, int(round(width * scale)))
    target_height = max(1, int(round(height * scale)))
    mark = mark.resized(target_width, target_height)

    foreground = pnglib.Image(canvas, canvas, bytearray(canvas * canvas * 4))
    foreground.paste(mark, (canvas - target_width) // 2, (canvas - target_height) // 2)
    pnglib.write_png(str(path), foreground)


def adaptive_icon_xml(background: str, foreground: str) -> str:
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by mobile/android/tools/make_android_icons.py -->\n"
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/%s" />\n'
        '    <foreground android:drawable="@mipmap/%s" />\n'
        '    <monochrome android:drawable="@mipmap/%s" />\n'
        "</adaptive-icon>\n" % (background, foreground, foreground)
    )


def main(argv: list) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Only report what would be generated.",
    )
    args = parser.parse_args(argv)

    if not SOURCE_ICON.exists():
        raise SystemExit(
            "Missing %s -- the icon generator needs the product icon." % SOURCE_ICON
        )

    image = pnglib.read_png(str(SOURCE_ICON))
    plate, glyph = iconart.build_art(image)
    left, top, width, height = iconart.orange_bounds(image)
    print(
        "Source: %s (%dx%d), orange plate at (%d, %d) %dx%d"
        % (SOURCE_ICON, image.width, image.height, left, top, width, height)
    )

    written: list = []

    for density, (launcher_size, foreground_size) in DENSITIES.items():
        directory = RES_DIR / ("mipmap-" + density)
        legacy = directory / "ic_launcher.png"
        legacy_round = directory / "ic_launcher_round.png"
        foreground = directory / "ic_launcher_foreground.png"
        for path, builder in (
            (legacy, lambda: write_legacy(plate, glyph, launcher_size, legacy)),
            (legacy_round, lambda: write_legacy(plate, glyph, launcher_size, legacy_round)),
            (foreground, lambda: write_foreground(glyph, foreground_size, foreground)),
        ):
            if args.check:
                print("would write %s" % path)
            else:
                builder()
                print("wrote %s" % path)
            written.append(path)

    # The adaptive background is the orange sampled from the product icon.
    sample = iconart.orange_sample(plate)
    background_colour = "%02X%02X%02X" % (sample[0], sample[1], sample[2])

    anydpi = RES_DIR / "mipmap-anydpi-v26"
    values = RES_DIR / "values"
    if not args.check:
        anydpi.mkdir(parents=True, exist_ok=True)
        values.mkdir(parents=True, exist_ok=True)

    xml = adaptive_icon_xml("ic_launcher_background", "ic_launcher_foreground")
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        path = anydpi / name
        if args.check:
            print("would write %s" % path)
        else:
            path.write_text(xml, encoding="utf-8")
            print("wrote %s" % path)
        written.append(path)

    colours = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by mobile/android/tools/make_android_icons.py -->\n"
        "<resources>\n"
        "    <!-- The orange sampled from icons/zode.png. -->\n"
        '    <color name="ic_launcher_background">#%s</color>\n'
        '    <color name="zode_orange">#FF4E00</color>\n'
        '    <color name="zode_ink">#141414</color>\n'
        '    <color name="zode_paper">#F4F2EF</color>\n'
        "</resources>\n" % background_colour
    )
    colours_path = values / "colors.xml"
    if args.check:
        print("would write %s" % colours_path)
    else:
        colours_path.write_text(colours, encoding="utf-8")
        print("wrote %s" % colours_path)
    written.append(colours_path)

    print("Generated %d files." % len(written))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
