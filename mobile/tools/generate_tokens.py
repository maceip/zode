REPO_ROOT = Path(__file__).resolve().parents[2]
TOKENS_CSS = REPO_ROOT / "packages" / "shared" / "tokens.css"

IOS_OUT = REPO_ROOT / "mobile" / "ios" / "ZodeMobile" / "Design" / "Tokens.swift"
ANDROID_OUT = (
    REPO_ROOT
    / "mobile"
    / "android"
    / "app"
    / "src"
    / "main"
    / "java"
    / "com"
    / "zode"
    / "app"
    / "design"
    / "Tokens.kt"
)

BANNER = (
    "// Generated by mobile/tools/generate_tokens.py\n"
    "// Source: packages/shared/tokens.css\n"
    "// DO NOT EDIT -- re-run the generator instead.\n"
)


def _swift_cgfloat(value: float) -> str:
    if float(value).is_integer():
        return "%d" % int(value)
    return ("%.4f" % value).rstrip("0").rstrip(".")


def _swift_double(value: float) -> str:
    text = ("%.4f" % value).rstrip("0").rstrip(".")
    return text if text else "0"


def _kotlin_sp(value: float) -> str:
    if float(value).is_integer():
        return "%d.sp" % int(value)
    return ("%s.sp" % (("%.4f" % value).rstrip("0").rstrip(".")))


def _kotlin_dp(value: float) -> str:
    if float(value).is_integer():
        return "%d.dp" % int(value)
    return ("%s.dp" % (("%.4f" % value).rstrip("0").rstrip(".")))


def _kotlin_float(value: float) -> str:
    """A Kotlin **Float** literal, e.g. `0.6275f`, `1f`, `0f`.

    Compose's `Color(red = …, green = …, blue = …, alpha = …)` and
    `floatArrayOf(…)` take Floats, so every fractional value needs the `f`
    suffix -- and a bare `0` would be an Int and would not compile at all.
    """
    text = ("%.4f" % value).rstrip("0").rstrip(".")
    if not text or text in ("-", "-0"):
        text = "0"
    if "." not in text:
        text += ".0"
    return text + "f"


def _kotlin_double(value: float) -> str:
    """A Kotlin **Double** literal, e.g. `220.0`."""
    text = ("%.4f" % value).rstrip("0").rstrip(".")
    if not text or text in ("-", "-0"):
        text = "0"
    if "." not in text:
        text += ".0"
    return text


def _swift_string(value: str) -> str:
    return '"%s"' % value.replace("\\", "\\\\").replace('"', '\\"')


def _kotlin_string(value: str) -> str:
    return '"%s"' % value.replace("\\", "\\\\").replace('"', '\\"')


def _sorted_names(tokens: Tokens, bucket: dict) -> list:
    return sorted(bucket.keys())


def render_swift(tokens: Tokens) -> str:
    out: list = [BANNER, "", "import SwiftUI", "", "public enum ZodeTokens {"]

    # ---- colours ----------------------------------------------------------
    out.append("    /// Every colour from `tokens.css`, verbatim.")
    out.append("    public enum Colors {")
    for name in _sorted_names(tokens, tokens.colors):
        out.append(
            "        public static let %s = %s"
            % (camel_case(name), tokens.colors[name].swift_literal())
        )
    out.append("    }")
    out.append("")

    # ---- type scale -------------------------------------------------------
    out.append("    /// Type scale, in points (the web app uses px at 1x).")
    out.append("    public enum TypeScale {")
    for name in _sorted_names(tokens, tokens.lengths):
        if not name.startswith("type-"):
            continue
        out.append(
            "        public static let %s: CGFloat = %s"
            % (camel_case(name), _swift_cgfloat(tokens.lengths[name]))
        )
    out.append("    }")
    out.append("")

    # ---- weights ----------------------------------------------------------
    out.append("    /// Font weights (the Segoe UI light/semibold family).")
    out.append("    public enum Weights {")
    for name in _sorted_names(tokens, tokens.weights):
        out.append(
            "        public static let %s: CGFloat = %s"
            % (camel_case(name), tokens.weights[name])
        )
    out.append("    }")
    out.append("")

    # ---- tracking ---------------------------------------------------------
    out.append("    /// Letter-spacing, in em.")
    out.append("    public enum Tracking {")
    for name in _sorted_names(tokens, tokens.em):
        out.append(
            "        public static let %s: CGFloat = %s"
            % (camel_case(name), _swift_cgfloat(tokens.em[name]))
        )
    out.append("    }")
    out.append("")

    # ---- metrics ----------------------------------------------------------
    out.append("    /// Layout metrics, in points.")
    out.append("    public enum Metrics {")
    for name in _sorted_names(tokens, tokens.lengths):
        if name.startswith("type-") or name.startswith("weight-"):
            continue
        out.append(
            "        public static let %s: CGFloat = %s"
            % (camel_case(name), _swift_cgfloat(tokens.lengths[name]))
        )
    out.append("    }")
    out.append("")

    # ---- motion -----------------------------------------------------------
    out.append("    /// Motion. Durations are milliseconds, matching the CSS.")
    out.append("    public enum Motion {")
    for name in _sorted_names(tokens, tokens.milliseconds):
        out.append(
            "        public static let %s: Double = %s"
            % (camel_case(name), _swift_double(tokens.milliseconds[name]))
        )
    for name in _sorted_names(tokens, tokens.beziers):
        bezier = tokens.beziers[name]
        out.append(
            "        public static let %s: [Double] = [%s, %s, %s, %s]"
            % (
                camel_case(name),
                _swift_double(bezier[0]),
                _swift_double(bezier[1]),
                _swift_double(bezier[2]),
                _swift_double(bezier[3]),
            )
        )
    out.append("")
    out.append("        /// Converts a CSS millisecond duration to seconds.")
    out.append("        public static func seconds(_ milliseconds: Double) -> Double {")
    out.append("            milliseconds / 1000.0")
    out.append("        }")
    out.append("    }")
    out.append("")

    # ---- fonts ------------------------------------------------------------
    out.append("    /// Font stacks, verbatim from `tokens.css`.")
    out.append("    public enum Fonts {")
    for name in _sorted_names(tokens, tokens.fonts):
        stack = ", ".join(_swift_string(p) for p in tokens.fonts[name])
        out.append(
            "        public static let %s: [String] = [%s]" % (camel_case(name), stack)
        )
    out.append("    }")
    out.append("")

    # ---- elevation --------------------------------------------------------
    out.append("    /// Elevation, derived from the CSS `box-shadow` values.")
    out.append("    public enum Elevation {")
    out.append("        public struct ShadowSpec {")
    out.append("            public let radius: CGFloat")
    out.append("            public let offsetX: CGFloat")
    out.append("            public let offsetY: CGFloat")
    out.append("            public let color: Color")
    out.append("            public let isInset: Bool")
    out.append("")
    out.append("            public init(radius: CGFloat, offsetX: CGFloat, offsetY: CGFloat, color: Color, isInset: Bool) {")
    out.append("                self.radius = radius")
    out.append("                self.offsetX = offsetX")
    out.append("                self.offsetY = offsetY")
    out.append("                self.color = color")
    out.append("                self.isInset = isInset")
    out.append("            }")
    out.append("        }")
    for name in _sorted_names(tokens, tokens.shadows):
        shadow = tokens.shadows[name]
        layers = ", ".join(
            "ShadowSpec(radius: %s, offsetX: %s, offsetY: %s, color: %s, isInset: %s)"
            % (
                _swift_cgfloat(layer.radius),
                _swift_cgfloat(layer.offset_x),
                _swift_cgfloat(layer.offset_y),
                layer.color.swift_literal() if layer.color else "Color.clear",
                "true" if layer.inset else "false",
            )
            for layer in shadow.layers
        )
        out.append("        public static let %s: [ShadowSpec] = [%s]" % (camel_case(name), layers))
    out.append("    }")
    out.append("}")

    out.append("")
    out.append("public extension Color {")
    out.append("    /// Builds a colour from a 24-bit RGB literal.")
    out.append("    init(hex: UInt32, alpha: Double = 1.0) {")
    out.append("        self.init(")
    out.append("            .sRGB,")
    out.append("            red: Double((hex >> 16) & 0xFF) / 255.0,")
    out.append("            green: Double((hex >> 8) & 0xFF) / 255.0,")
    out.append("            blue: Double(hex & 0xFF) / 255.0,")
    out.append("            opacity: alpha")
    out.append("        )")
    out.append("    }")
    out.append("}")
    out.append("")
    return "\n".join(out)


def render_kotlin(tokens: Tokens) -> str:
    out: list = [
        "// Generated by mobile/tools/generate_tokens.py",
        "// Source: packages/shared/tokens.css",
        "// DO NOT EDIT -- re-run the generator instead.",
        "",
        "package com.zode.app.design",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.unit.dp",
        "import androidx.compose.ui.unit.sp",
        "",
        "object ZodeTokens {",
    ]

    out.append("    /** Every colour from `tokens.css`, verbatim. */")
    out.append("    object Colors {")
    for name in _sorted_names(tokens, tokens.colors):
        out.append(
            "        val %s = %s"
            % (camel_case(name), tokens.colors[name].kotlin_literal())
        )
    out.append("    }")
    out.append("")

    out.append("    /** Type scale, in sp (the web app uses px at 1x). */")
    out.append("    object TypeScale {")
    for name in _sorted_names(tokens, tokens.lengths):
        if not name.startswith("type-"):
            continue
        out.append(
            "        val %s = %s" % (camel_case(name), _kotlin_sp(tokens.lengths[name]))
        )
    out.append("    }")
    out.append("")

    out.append("    /** Font weights (the Segoe UI light/semibold family). */")
    out.append("    object Weights {")
    for name in _sorted_names(tokens, tokens.weights):
        out.append("        val %s = %d" % (camel_case(name), tokens.weights[name]))
    out.append("    }")
    out.append("")

    out.append("    /** Letter-spacing, in em. */")
    out.append("    object Tracking {")
    for name in _sorted_names(tokens, tokens.em):
        out.append("        val %s = %s" % (camel_case(name), _kotlin_float(tokens.em[name])))
    out.append("    }")
    out.append("")

    out.append("    /** Layout metrics, in dp. */")
    out.append("    object Metrics {")
    for name in _sorted_names(tokens, tokens.lengths):
        if name.startswith("type-") or name.startswith("weight-"):
            continue
        out.append(
            "        val %s = %s" % (camel_case(name), _kotlin_dp(tokens.lengths[name]))
        )
    out.append("    }")
    out.append("")

    out.append("    /** Motion. Durations are milliseconds, matching the CSS. */")
    out.append("    object Motion {")
    for name in _sorted_names(tokens, tokens.milliseconds):
        out.append(
            "        const val %s: Double = %s"
            % (camel_case(name), _kotlin_double(tokens.milliseconds[name]))
        )
    for name in _sorted_names(tokens, tokens.beziers):
        bezier = tokens.beziers[name]
        out.append(
            "        val %s = floatArrayOf(%s, %s, %s, %s)"
            % (
                camel_case(name),
                _kotlin_float(bezier[0]),
                _kotlin_float(bezier[1]),
                _kotlin_float(bezier[2]),
                _kotlin_float(bezier[3]),
            )
        )
    out.append("")
    out.append("        /** Converts a CSS millisecond duration to seconds. */")
    out.append("        fun seconds(milliseconds: Double): Double = milliseconds / 1000.0")
    out.append("    }")
    out.append("")

    out.append("    /** Font stacks, verbatim from `tokens.css`. */")
    out.append("    object Fonts {")
    for name in _sorted_names(tokens, tokens.fonts):
        stack = ", ".join(_kotlin_string(p) for p in tokens.fonts[name])
        out.append("        val %s = listOf(%s)" % (camel_case(name), stack))
    out.append("    }")
    out.append("")

    out.append("    /** Elevation, derived from the CSS `box-shadow` values. */")
    out.append("    object Elevation {")
    out.append("        data class ShadowSpec(")
    out.append("            val radius: Float,")
    out.append("            val offsetX: Float,")
    out.append("            val offsetY: Float,")
    out.append("            val color: Color,")
    out.append("            val isInset: Boolean")
    out.append("        )")
    for name in _sorted_names(tokens, tokens.shadows):
        shadow = tokens.shadows[name]
        layers = ", ".join(
            "ShadowSpec(%s, %s, %s, %s, %s)"
            % (
                _kotlin_float(layer.radius),
                _kotlin_float(layer.offset_x),
                _kotlin_float(layer.offset_y),
                layer.color.kotlin_literal() if layer.color else "Color.Transparent",
                "true" if layer.inset else "false",
            )
            for layer in shadow.layers
        )
        out.append("        val %s = listOf(%s)" % (camel_case(name), layers))
    out.append("    }")
    out.append("}")
    out.append("")
    return "\n".join(out)


def write_if_changed(path: Path, content: str, check: bool) -> bool:
    if check:
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != content:
            print("STALE: %s" % path)
            return False
        print("OK (unchanged): %s" % path)
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print("Wrote: %s" % path)
    return True


def main(argv: list) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--platform",
        choices=["ios", "android", "both"],
        default="both",
        help="Which generated file(s) to write.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Do not write; exit non-zero if a generated file is stale.",
    )
    args = parser.parse_args(argv)

    if not TOKENS_CSS.exists():
        print("Missing %s" % TOKENS_CSS)
        return 1

    tokens = parse_tokens(TOKENS_CSS.read_text(encoding="utf-8"))
    print(
        "Parsed %d tokens from %s (%d colours, %d lengths, %d weights, %d easings)"
        % (
            len(tokens.raw),
            TOKENS_CSS.relative_to(REPO_ROOT),
            len(tokens.colors),
            len(tokens.lengths),
            len(tokens.weights),
            len(tokens.beziers),
        )
    )

    ok = True
    if args.platform in ("ios", "both"):
        ok = write_if_changed(IOS_OUT, render_swift(tokens), args.check) and ok
    if args.platform in ("android", "both"):
        ok = write_if_changed(ANDROID_OUT, render_kotlin(tokens), args.check) and ok

    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
