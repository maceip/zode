"""Generate the Swift and Kotlin design-token files from `packages/shared/tokens.css`.

Usage:
    python3 mobile/tools/generate_tokens.py                 # regenerate both
    python3 mobile/tools/generate_tokens.py --platform ios
    python3 mobile/tools/generate_tokens.py --platform android
    python3 mobile/tools/generate_tokens.py --check         # fail if stale

The generator is deterministic: identical input produces byte-identical output.
"""

