#!/usr/bin/env python3
"""Generate the haptic program files from `packages/shared/haptics.json`.

Usage:
    python3 mobile/tools/generate_haptics.py
    python3 mobile/tools/generate_haptics.py --platform ios
    python3 mobile/tools/generate_haptics.py --platform android
    python3 mobile/tools/generate_haptics.py --check

Both mobile apps render THESE programs -- the generated files carry the exact
timings, carrier frequencies and intensity/sharpness curves from the shared
JSON, and both apps additionally re-read the JSON that ships in the app bundle
so the bundled file stays the single source of truth at runtime.
"""

